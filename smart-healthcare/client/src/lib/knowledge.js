export function getBotReply(raw) {
  const text = raw.toLowerCase();
  let best = null;
  let bestScore = 0;
  for (const item of KNOWLEDGE) {
    let score = 0;
    for (const kw of item.keywords) {
      if (text.includes(kw)) score += kw.length;
    }
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  }
  if (!best) return FALLBACK;

  const r = best.reply;
  return `${best.name}\n\n${r.summary}\n\nHome care:\n${r.homeCare}\nWhen to see a doctor:\n${r.seeDoctor}`;
}

